"""The screen's fonts, rendered from TrueType into 4-bit alpha glyphs: src/gen/od_fonts.h

  gen_fonts.py OUT.h

Faces (SIL Open Font License 1.1, LICENSES/*-OFL.txt): Silkscreen (labels), Inter Tight (values, the
splash). A glyph: its box (w x h), its offset from the pen (x, y from the baseline up to the box's top), its advance;
pixels as nibbles, rows back to back, the first pixel in the high nibble.
"""
import sys
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

HERE = Path(__file__).resolve().parent
ASCII = "".join(chr(c) for c in range(32, 127))

# name, file, size px, weight (variable fonts), characters, oversampling (pixel faces: 1, crisp)
FACES = [
    ("SILK8", "Silkscreen-Regular.ttf", 8, None, ASCII, 1),
    ("VAL10", "InterTight.ttf", 10, 500, ASCII, 4),
    ("VAL11", "InterTight.ttf", 11.5, 600, ASCII, 4),
    ("INT36", "InterTight.ttf", 36, 800, "OndaDrem", 4),
    ("INT10B", "InterTight.ttf", 10, 800, ASCII, 4),
    ("INT11", "InterTight.ttf", 11, 600, ASCII, 4),
    ("INT7", "InterTight.ttf", 7.5, 500, ASCII, 4),
]


def face(fname, size, weight, ov):
    f = ImageFont.truetype(str(HERE / fname), size=int(round(size * ov)))
    if weight:
        try:
            f.set_variation_by_axes([weight])
        except Exception:
            pass
    return f


def glyph(f, ch, ov):
    asc, desc = f.getmetrics()
    adv = f.getlength(ch)
    pad = 4 * ov
    img = Image.new("L", (int(adv) + 2 * pad + 4 * ov, asc + desc + 2 * pad), 0)
    ImageDraw.Draw(img).text((pad, pad), ch, font=f, fill=255)
    if ov > 1:                                   # align the box to the oversampling grid, then down
        W, H = img.width // ov * ov, img.height // ov * ov
        img = img.crop((0, 0, W, H)).resize((W // ov, H // ov), Image.LANCZOS)
        pad //= ov
        asc = round(asc / ov)
        adv /= ov
    else:                                        # pixel faces: hard edges
        img = img.point(lambda v: 255 if v >= 128 else 0)
    bb = img.getbbox()
    if not bb:
        return dict(w=0, h=0, x=0, y=0, adv=round(adv), px=[])
    img = img.crop(bb)
    px = [min(15, (v + 8) // 17) for v in img.tobytes()]
    return dict(w=img.width, h=img.height, x=bb[0] - pad, y=(pad + asc) - bb[1], adv=round(adv), px=px)


def main(out):
    L = ["/* generated by tools/gen_fonts.py: the screen's fonts (SIL OFL 1.1 faces), 4-bit alpha */",
         "#pragma once", "#include <stdint.h>", "",
         "typedef struct { uint16_t off; uint8_t w, h; int8_t x, y; uint8_t adv; } od_glyph_t;",
         "typedef struct { const od_glyph_t *g; const uint8_t *px; const char *chars; uint8_t n, asc, h; } od_font_t;", ""]
    for name, fname, size, weight, chars, ov in FACES:
        f = face(fname, size, weight, ov)
        gl, data, off = [], [], 0
        for ch in chars:
            g = glyph(f, ch, ov)
            px = g["px"]
            if len(px) % 2:
                px = px + [0]
            data += [px[i] << 4 | px[i + 1] for i in range(0, len(px), 2)]
            gl.append((off, g))
            off += len(px) // 2
        asc = max(g["y"] for _, g in gl)
        h = max(g["y"] for _, g in gl) + max(g["h"] - g["y"] for _, g in gl)
        L.append(f"static const uint8_t FPX_{name}[{max(1, len(data))}] = {{")
        for i in range(0, len(data), 32):
            L.append("    " + ",".join(str(b) for b in data[i:i + 32]) + ",")
        if not data:
            L.append("    0,")
        L.append("};")
        L.append(f"static const od_glyph_t FG_{name}[{len(gl)}] = {{")
        for o, g in gl:
            L.append(f"    {{{o}, {g['w']}, {g['h']}, {g['x']}, {g['y']}, {g['adv']}}},")
        L.append("};")
        esc = chars.replace("\\", "\\\\").replace('"', '\\"')
        L.append(f'static const od_font_t F_{name} = {{FG_{name}, FPX_{name}, "{esc}", {len(gl)}, {asc}, {h}}};')
        L.append("")
        print(f"font {name}: {len(gl)} glyphs, {len(data)} B")
    Path(out).write_text("\n".join(L))


if __name__ == "__main__":
    main(sys.argv[1])
