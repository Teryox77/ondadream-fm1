// The screen's fonts, drawn by the same browser engine that drew the preview (Chromium's canvas, through Playwright),
// so the letters on the FM-1 are the preview's, pixel for pixel: src/gen/od_fonts.h
//
//   node tools/gen_fonts.js src/gen/od_fonts.h      (needs: npm i playwright, and its Chromium)
//
// Faces (SIL Open Font License 1.1, LICENSES/*-OFL.txt): Silkscreen (labels), Pixelify Sans (values),
// Inter Tight (the splash). A glyph: its box (w x h), its offset from the pen (x, y from the baseline up to the box's
// top), its advance in 1/16 px; pixels as 4-bit alpha nibbles, rows back to back, the first pixel in the high nibble.
const fs = require('fs'), path = require('path'), http = require('http');
const { chromium } = require('playwright');
const HERE = __dirname;
const ASCII = Array.from({ length: 95 }, (_, i) => String.fromCharCode(32 + i)).join('');
// name, CSS font, characters: as the preview's canvas sets them
const FACES = [
  ['SILK8', "8px SILK", ASCII],                 // txt(..., 8, SILK)
  ['PX10M', "500 10px PX", ASCII],              // label(): the scenes' texts
  ['PX7M', "500 7.5px PX", ASCII],              // label() on ENVELOPE, whose scene is drawn at .75
  ['PX11', "11px PX", ASCII],                   // the cards' values
  ['PX10', "10px PX", ASCII],                   // GLOBAL's values
  ['INT36', "800 36px IT", 'OndaDrem'],         // the splash
  ['INT10B', "800 10px IT", ASCII],
  ['INT11', "600 11px IT", ASCII],
  ['INT7', "500 7.5px IT", ASCII],
];
const PAGE = `<!doctype html><style>
@font-face{font-family:SILK;src:url(Silkscreen-Regular.ttf)}
@font-face{font-family:PX;src:url(PixelifySans.ttf);font-weight:400 700}
@font-face{font-family:IT;src:url(InterTight.ttf);font-weight:100 900}</style><canvas id=c width=96 height=96></canvas>`;

(async () => {
  const srv = http.createServer((q, r) => {
    if (q.url === '/') { r.writeHead(200, { 'content-type': 'text/html' }); return r.end(PAGE); }
    const f = path.join(HERE, decodeURIComponent(q.url.slice(1)));
    if (!f.startsWith(HERE) || !fs.existsSync(f)) { r.writeHead(404); return r.end(); }
    r.writeHead(200, { 'content-type': 'font/ttf' }); r.end(fs.readFileSync(f));
  }).listen(0);
  const b = await chromium.launch();
  const p = await b.newPage({ deviceScaleFactor: 1 });
  await p.goto(`http://localhost:${srv.address().port}/`);
  const L = ['/* generated by tools/gen_fonts.js: the screen\'s fonts as the preview\'s canvas draws them (SIL OFL 1.1 faces), 4-bit alpha */',
    '#pragma once', '#include <stdint.h>', '',
    'typedef struct { uint16_t off; uint8_t w, h; int8_t x, y; uint16_t adv16; } od_glyph_t;   /* adv16: 1/16 px */',
    'typedef struct { const od_glyph_t *g; const uint8_t *px; const char *chars; uint8_t n, asc, h; } od_font_t;', ''];
  for (const [name, css, chars] of FACES) {
    const gl = await p.evaluate(async ([css, chars]) => {
      await document.fonts.load(css);
      const c = document.getElementById('c'), g = c.getContext('2d', { willReadFrequently: true }), out = [];
      for (const ch of chars) {
        g.setTransform(1, 0, 0, 1, 0, 0); g.fillStyle = '#000'; g.fillRect(0, 0, 96, 96);
        g.font = css; g.fillStyle = '#fff'; g.textBaseline = 'alphabetic'; g.textAlign = 'left';
        g.fillText(ch, 24, 64);
        const d = g.getImageData(0, 0, 96, 96).data;
        let x0 = 96, y0 = 96, x1 = -1, y1 = -1;
        for (let y = 0; y < 96; y++) for (let x = 0; x < 96; x++) if (d[(y * 96 + x) * 4] > 8) { x0 = Math.min(x0, x); x1 = Math.max(x1, x); y0 = Math.min(y0, y); y1 = Math.max(y1, y); }
        const adv = g.measureText(ch).width;
        if (x1 < 0) { out.push({ w: 0, h: 0, x: 0, y: 0, adv, px: [] }); continue; }
        const px = [];
        for (let y = y0; y <= y1; y++) for (let x = x0; x <= x1; x++) px.push(Math.min(15, Math.round(d[(y * 96 + x) * 4] / 17)));
        out.push({ w: x1 - x0 + 1, h: y1 - y0 + 1, x: x0 - 24, y: 64 - y0, adv, px });
      }
      return out;
    }, [css, chars]);
    const data = [], rows = []; let off = 0;
    for (const g of gl) {
      const px = g.px.length % 2 ? g.px.concat([0]) : g.px;
      for (let i = 0; i < px.length; i += 2) data.push(px[i] << 4 | px[i + 1]);
      rows.push(`    {${off}, ${g.w}, ${g.h}, ${g.x}, ${g.y}, ${Math.round(g.adv * 16)}},`);
      off += px.length / 2;
    }
    const asc = Math.max(...gl.map(g => g.y)), h = asc + Math.max(...gl.map(g => g.h - g.y));
    L.push(`static const uint8_t FPX_${name}[${Math.max(1, data.length)}] = {`);
    for (let i = 0; i < data.length; i += 32) L.push('    ' + data.slice(i, i + 32).join(',') + ',');
    if (!data.length) L.push('    0,');
    L.push('};', `static const od_glyph_t FG_${name}[${gl.length}] = {`, ...rows, '};');
    L.push(`static const od_font_t F_${name} = {FG_${name}, FPX_${name}, "${chars.replace(/\\/g, '\\\\').replace(/"/g, '\\"')}", ${gl.length}, ${asc}, ${h}};`, '');
    console.log(`font ${name} (${css}): ${gl.length} glyphs, ${data.length} B`);
  }
  fs.writeFileSync(process.argv[2], L.join('\n'));
  await b.close(); srv.close();
})();
