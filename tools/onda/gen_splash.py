"""OndaDream: the splash's texts as 4-bit alpha bitmaps (gfx.c cv_alpha's format: w x h nibbles, rows back to back,
the first pixel in the high nibble), rendered from the firmware's own face (assets/fonts/InterTight[wght].ttf).

  gen_splash.py OUT.h

The version comes from firmware/src/ui_draw.c (ONDA_VERSION), so the splash always shows the built version.
"""
import re
import sys
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[2]
TTF = ROOT / "assets" / "fonts" / "InterTight[wght].ttf"

# name, text, size px, weight, tracking px (between letters)
def texts(version):
    return [("ONDA", "Onda", 36, 800, -1.0),
            ("DREAM", "Dream", 36, 800, -1.0),
            ("VER", version, 10, 800, 0.0),
            ("AUTHOR", "Teryox77", 11, 600, 0.0),
            ("CREDIT", "FOR FELUCCA 1.8", 7.5, 500, 0.6)]


def render(text, size, weight, tracking):
    f = ImageFont.truetype(str(TTF), size=int(round(size * 4)))       # 4x, then down: smooth coverage
    try:
        f.set_variation_by_axes([weight])
    except Exception:
        pass
    asc, desc = f.getmetrics()
    w = sum(f.getlength(c) for c in text) + tracking * 4 * (len(text) - 1) + 8
    img = Image.new("L", (int(w) + 8, asc + desc + 8), 0)
    d = ImageDraw.Draw(img)
    x = 4
    for c in text:
        d.text((x, 4), c, font=f, fill=255)
        x += f.getlength(c) + tracking * 4
    bb = img.getbbox()
    img = img.crop(bb)
    base = asc + 4 - bb[1]                           # the baseline, from the bitmap's top, at 4x
    W, H = (img.width + 3) // 4, (img.height + 3) // 4
    img = img.resize((W, H), Image.LANCZOS)
    return img, round(base / 4)


def main(out):
    src = (ROOT / "firmware" / "src" / "ui_draw.c").read_text(encoding="latin-1")
    version = re.search(r'#define ONDA_VERSION "([^"]+)"', src).group(1)
    lines = ["/* generated by tools/onda/gen_splash.py: the OndaDream splash's texts, 4-bit alpha (cv_alpha) */",
             "#pragma once", "#include <stdint.h>", ""]
    for name, text, size, weight, tr in texts(version):
        img, base = render(text, size, weight, tr)
        px = [min(15, (v + 8) // 17) for v in img.tobytes()]
        if len(px) % 2:
            px.append(0)
        data = [px[i] << 4 | px[i + 1] for i in range(0, len(px), 2)]
        lines.append(f"/* \"{text}\" {size} px, weight {weight}: {img.width} x {img.height}, baseline {base} */")
        lines.append(f"#define SPL_{name}_W {img.width}")
        lines.append(f"#define SPL_{name}_H {img.height}")
        lines.append(f"#define SPL_{name}_BASE {base}")
        lines.append(f"static const uint8_t SPL_{name}[{len(data)}] = {{")
        for i in range(0, len(data), 24):
            lines.append("    " + ", ".join(str(b) for b in data[i:i + 24]) + ",")
        lines.append("};")
        lines.append("")
    Path(out).write_text("\n".join(lines))
    print(f"splash: {version} -> {out}")


if __name__ == "__main__":
    main(sys.argv[1])
