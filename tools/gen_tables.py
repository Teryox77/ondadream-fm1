"""Generated tables and presets for the OndaDream core: src/gen/od_tables.h

  gen_tables.py OUT.h
"""
import json
import math
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
FS = 44100


def arr(name, ctype, vals, per=16):
    out = [f"static const {ctype} {name}[{len(vals)}] = {{"]
    for i in range(0, len(vals), per):
        out.append("    " + ", ".join(str(v) for v in vals[i:i + per]) + ",")
    out.append("};")
    return out


def main(out):
    L = ["/* generated by tools/gen_tables.py: OndaDream core tables and presets */", "#pragma once", "#include <stdint.h>", "",
         f"#define OD_FS {FS}"]
    # a full sine turn in 1024 steps (+1: interpolation needs no wrap), Q15
    L += arr("OD_SINE", "int16_t", [round(32767 * math.sin(2 * math.pi * i / 1024)) for i in range(1025)])
    # tanh over -4..+4 in 512 steps (+1), Q15: the master's soft clip
    L += arr("OD_TANH", "int16_t", [round(32767 * math.tanh(-4 + 8 * i / 512)) for i in range(513)])
    # 2^(i/256) for i in 0..256, Q15 after a shift: as Q30 / 2^15 (exp2 of the fraction)
    L += arr("OD_EXP2F", "uint16_t", [round(32768 * (2 ** (i / 256)) - 32768) for i in range(257)])
    # presets: OndaDream's 43 sounds, as the web synth has them
    keys = ["wave", "detune", "oscMix", "drive", "cutoff", "reso", "fEnvAmt", "keyTrk", "a", "d", "s", "r",
            "lfoRate", "lfoPitch", "lfoCut", "fDecay", "vol", "arpPattern", "arpBpm", "arpOct", "arpGate",
            "cho", "eco", "etime", "rev"]
    pr = json.load(open(HERE / "presets.json"))
    L += ["", f"#define OD_NPRESETS {len(pr)}",
          "typedef struct { const char *name; float " + ", ".join(keys) + "; } od_preset_t;",
          "static const od_preset_t OD_PRESETS[OD_NPRESETS] = {"]
    for p in pr:
        v = p["p"]
        name = p["name"].replace("À", "A'").replace("à", "a'")
        L.append(f'    {{"{name}", ' + ", ".join(f"{float(v[k]):.6g}".rstrip() + ("f" if "." in f"{float(v[k]):.6g}" or "e" in f"{float(v[k]):.6g}" else ".0f") for k in keys) + "},")
    L += ["};", ""]
    Path(out).write_text("\n".join(L))
    print(f"tables: {len(pr)} presets -> {out}")


if __name__ == "__main__":
    main(sys.argv[1])
